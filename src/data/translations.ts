const warnedTranslationKeys = new Set<string>();

if (import.meta.env?.DEV) {
  const enKeys = Object.keys(translations.en) as TranslationKey[];
  const bhoDict = translations.bho as Record<string, string>;
  const maiDict = translations.mai as Record<string, string>;
  const neDict = translations.ne as Record<string, string>;
  const hiDict = translations.hi as Record<string, string>;
  for (const key of enKeys) {
    if (!bhoDict[key] || !bhoDict[key].trim()) {
      console.warn(`[i18n:bho] Missing Bhojpuri translation key in translations.ts: "${key}"`);
    }
    if (!maiDict[key] || !maiDict[key].trim()) {
      console.warn(`[i18n:mai] Missing Maithili translation key in translations.ts: "${key}"`);
    }
    if (!neDict[key] || !neDict[key].trim()) {
      console.warn(`[i18n:ne] Missing Nepali translation key in translations.ts: "${key}"`);
    }
    if (!hiDict[key] || !hiDict[key].trim()) {
      console.warn(`[i18n:hi] Missing Hindi translation key in translations.ts: "${key}"`);
    }
  }
}

export function getTranslation(lang: 'en' | 'ne' | 'hi' | 'bho' | 'mai', key: TranslationKey): string {
  const dict = translations[lang] as Record<string, string> | undefined;
  const val = dict?.[key];
  if (val && val.trim() !== '') return val;
  if (import.meta.env?.DEV) {
    const sig = `${lang}:${key}`;
    if (!warnedTranslationKeys.has(sig)) {
      warnedTranslationKeys.add(sig);
      console.warn(`[i18n:${lang}] Missing key "${key}" in translations.ts`);
    }
  }
  return translations.en[key];
}

