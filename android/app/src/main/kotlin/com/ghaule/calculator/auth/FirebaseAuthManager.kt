package com.ghaule.calculator.auth

import android.app.Activity
import android.content.Context
import android.util.Log
import android.webkit.JavascriptInterface
import android.webkit.WebView
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.ghaule.calculator.BuildConfig
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.SetOptions
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext
import org.json.JSONObject

/**
 * Native Google Sign-In using Android Credential Manager + Firebase Auth.
 * Reads real OAuth Web Client ID from BuildConfig.GOOGLE_WEB_CLIENT_ID or
 * default_web_client_id generated by the google-services plugin from google-services.json.
 */
class FirebaseAuthManager(
    private val activity: Activity,
    private val webView: WebView
) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
    private val credentialManager by lazy { CredentialManager.create(activity) }

    companion object {
        private const val TAG = "GauleAuthBridge"
    }

    private fun resolveWebClientId(context: Context): String? {
        val fromBuildConfig = BuildConfig.GOOGLE_WEB_CLIENT_ID.trim()
        if (fromBuildConfig.isNotEmpty() && !fromBuildConfig.contains("YOUR_REAL", ignoreCase = true)) {
            return fromBuildConfig
        }
        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId != 0) {
            val fromRes = context.getString(resId).trim()
            if (fromRes.isNotEmpty() && !fromRes.contains("PLACEHOLDER", ignoreCase = true)) {
                return fromRes
            }
        }
        return null
    }

    @JavascriptInterface
    fun signInWithGoogle() {
        activity.runOnUiThread {
            scope.launch {
                try {
                    if (FirebaseApp.getApps(activity).isEmpty()) {
                        dispatchError(
                            "DEVELOPER_CONFIG_MISSING",
                            "Firebase google-services.json is missing from android/app/. Add real Firebase Android config before building release APK."
                        )
                        return@launch
                    }

                    val webClientId = resolveWebClientId(activity)
                    if (webClientId.isNullOrBlank()) {
                        dispatchError(
                            "DEVELOPER_ERROR_NO_CLIENT_ID",
                            "Missing Web OAuth Client ID (default_web_client_id or GOOGLE_WEB_CLIENT_ID in local.properties)."
                        )
                        return@launch
                    }

                    val googleIdOption = GetGoogleIdOption.Builder()
                        .setFilterByAuthorizedAccounts(false)
                        .setServerClientId(webClientId)
                        .setAutoSelectEnabled(false)
                        .build()

                    val request = GetCredentialRequest.Builder()
                        .addCredentialOption(googleIdOption)
                        .build()

                    val result = withContext(Dispatchers.IO) {
                        credentialManager.getCredential(
                            request = request,
                            context = activity
                        )
                    }

                    val credential = result.credential
                    if (credential is CustomCredential &&
                        credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
                    ) {
                        val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                        val idToken = googleIdTokenCredential.idToken

                        val firebaseCredential = GoogleAuthProvider.getCredential(idToken, null)
                        val authResult = withContext(Dispatchers.IO) {
                            FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await()
                        }

                        val fbUser = authResult.user
                        if (fbUser != null) {
                            syncUserProfileToFirestore(
                                uid = fbUser.uid,
                                name = fbUser.displayName ?: googleIdTokenCredential.displayName ?: "Google User",
                                email = fbUser.email ?: googleIdTokenCredential.id,
                                photoUrl = fbUser.photoUrl?.toString()
                            )

                            val payload = JSONObject().apply {
                                put("success", true)
                                put("uid", fbUser.uid)
                                put("email", fbUser.email ?: "")
                                put("name", fbUser.displayName ?: "Google User")
                                put("photoUrl", fbUser.photoUrl?.toString() ?: "")
                                put("idToken", idToken)
                            }
                            dispatchResult(payload)
                        } else {
                            dispatchError("AUTH_USER_NULL", "Firebase returned null user after credential sign-in.")
                        }
                    } else {
                        dispatchError("UNEXPECTED_CREDENTIAL", "Received unsupported credential type from Credential Manager.")
                    }
                } catch (e: GetCredentialCancellationException) {
                    val cancelJson = JSONObject().apply {
                        put("success", false)
                        put("cancelled", true)
                        put("code", "12501")
                        put("message", "Google account selection was cancelled by user.")
                    }
                    dispatchResult(cancelJson)
                } catch (e: NoCredentialException) {
                    dispatchError(
                        "NO_CREDENTIAL",
                        "No Google account available on device or OAuth SHA-1 fingerprint mismatch in Firebase Console."
                    )
                } catch (e: GetCredentialException) {
                    Log.e(TAG, "Credential Manager error", e)
                    dispatchError("CREDENTIAL_ERROR", e.localizedMessage ?: "Credential Manager failed.")
                } catch (e: Throwable) {
                    Log.e(TAG, "Native Google Sign-In failure", e)
                    dispatchError("AUTH_FAILED", e.localizedMessage ?: "Google Sign-In failed.")
                }
            }
        }
    }

    @JavascriptInterface
    fun signOut() {
        activity.runOnUiThread {
            scope.launch {
                try {
                    withContext(Dispatchers.IO) {
                        if (FirebaseApp.getApps(activity).isNotEmpty()) {
                            FirebaseAuth.getInstance().signOut()
                        }
                        credentialManager.clearCredentialState(ClearCredentialStateRequest())
                    }
                } catch (t: Throwable) {
                    Log.w(TAG, "SignOut warning", t)
                }
            }
        }
    }

    private suspend fun syncUserProfileToFirestore(
        uid: String,
        name: String,
        email: String,
        photoUrl: String?
    ) {
        withContext(Dispatchers.IO) {
            try {
                val data = hashMapOf<String, Any>(
                    "uid" to uid,
                    "name" to name,
                    "email" to email,
                    "provider" to "google.com",
                    "lastLogin" to System.currentTimeMillis(),
                    "accountStatus" to "active"
                )
                if (!photoUrl.isNullOrBlank()) {
                    data["photoURL"] = photoUrl
                }
                FirebaseFirestore.getInstance()
                    .collection("users")
                    .document(uid)
                    .set(data, SetOptions.merge())
                    .await()
            } catch (e: Throwable) {
                Log.w(TAG, "Profile Firestore sync warning: ${e.message}")
            }
        }
    }

    private fun dispatchError(code: String, message: String) {
        val json = JSONObject().apply {
            put("success", false)
            put("cancelled", false)
            put("code", code)
            put("message", message)
        }
        dispatchResult(json)
    }

    private fun dispatchResult(json: JSONObject) {
        val escaped = JSONObject.quote(json.toString())
        val js = "if (window.onAndroidGoogleSignInResult) { window.onAndroidGoogleSignInResult(JSON.parse($escaped)); }"
        webView.post {
            webView.evaluateJavascript(js, null)
        }
    }
}
